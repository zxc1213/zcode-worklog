/**
 * Build the installable plugin:
 *   - dist/server.mjs  (bundled MCP server, no node_modules needed)
 *   - dist/panel.js    (bundled MCP App, classic script)
 *   - dist/panel.html / dist/panel.css
 */
import { copyFile, mkdir, stat } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const ROOT = dirname(fileURLToPath(import.meta.url)).replace(/[\\/]scripts$/, '')
const DIST = join(ROOT, 'dist')

await mkdir(DIST, { recursive: true })

await build({
  entryPoints: [join(ROOT, 'src', 'server.mjs')],
  outfile: join(DIST, 'server.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: '// zcode-worklog MCP server (bundled). Generated by scripts/build.mjs.',
  },
})

await build({
  entryPoints: [join(ROOT, 'hooks', 'session-start.mjs')],
  outfile: join(DIST, 'session-start.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: '// zcode-worklog SessionStart hook (bundled). Generated by scripts/build.mjs.',
  },
})

await build({
  entryPoints: [join(ROOT, 'src', 'panel.js')],
  outfile: join(DIST, 'panel.js'),
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['chrome110', 'safari16', 'firefox110'],
  sourcemap: false,
  legalComments: 'none',
  minify: true,
  banner: {
    js: '/* zcode-worklog panel (bundled). Generated by scripts/build.mjs. */',
  },
})

await copyFile(join(ROOT, 'src', 'panel.html'), join(DIST, 'panel.html'))
await copyFile(join(ROOT, 'src', 'panel.css'), join(DIST, 'panel.css'))

for (const name of ['server.mjs', 'session-start.mjs', 'panel.js', 'panel.html', 'panel.css']) {
  const info = await stat(join(DIST, name))
  console.log(`${name.padEnd(12)} ${(info.size / 1024).toFixed(1)} KB`)
}
